const DICTS: Record<Language, Record<ChainKey, string>> = { en, zh };

export function ct(lang: Language, key: ChainKey, values: Record<string, string | number> = {}): string {
  const template = DICTS[lang][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in values ? String(values[name]) : `{${name}}`));
}

export const hasChainKey = (key: string): key is ChainKey => key in en;
export const CHAIN_KEYS = Object.keys(en) as ChainKey[];
export const chainDict = (lang: Language) => DICTS[lang];
