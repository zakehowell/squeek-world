const paths = {};
for (const [name, rows] of Object.entries(GRIDS)) {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === "#") end++;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  paths[name] = d;
}

export const PIXEL_ICON_NAMES = Object.freeze(Object.keys(GRIDS));

/** Icon sizes snap to multiples of 6 px so every grid pixel stays whole on 2× screens. */
export function pixelIconSize(size = 18) {
  return Math.max(12, Math.round(size / 6) * 6);
}

export function pixelIcon(name, size = 18) {
  const d = paths[name];
  if (!d) return "";
  const px = pixelIconSize(size);
  return `<svg class="px-icon" width="${px}" height="${px}" viewBox="0 0 12 12" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path d="${d}"/></svg>`;
}
