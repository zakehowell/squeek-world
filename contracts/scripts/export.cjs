// Writes what the World and the deploy page need from the compiled contracts:
//   ../src/world/chain/abi.ts  the functions the World calls, every custom error, with selectors
//   deploy/contracts.js        ABI and bytecode of the four contracts, for the deploy page
// Run after `hardhat compile` (npm run export). `--check` only compares, for the tests.
const fs = require("node:fs");
const path = require("node:path");
const { ethers } = require("ethers");

const ROOT = path.resolve(__dirname, "..");
const CONTRACTS = ["SqbToken", "SqbMinter", "WorldShop", "SqkFaucet"];

// What the World calls. SQK is called through SqbToken's ERC-20 + permit functions, which the
// official SQK has too.
const USED = {
  SqbToken: ["balanceOf", "allowance", "approve", "nonces", "eip712Domain"],
  SqbMinter: ["account", "stake", "stakeWithPermit", "unstake", "claim", "sync"],
  WorldShop: [
    "prices",
    "seasonOneStart",
    "overview",
    "deedsInRange",
    "guildsInRange",
    "decorationHistory",
    "seasonSupply",
    "buyDeed",
    "buyDeedWithPermit",
    "nameDeed",
    "renovate",
    "renovateWithPermit",
    "foundGuild",
    "foundGuildWithPermit",
    "joinGuild",
    "supply",
    "supplyWithPermit",
    "buyDecoration",
    "buyDecorationWithPermit",
  ],
  SqkFaucet: ["status", "drip"],
};

function artifact(name) {
  const file = path.join(ROOT, "artifacts", "src", `${name}.sol`, `${name}.json`);
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

/** An ABI parameter without the compiler's internalType noise. */
function param(p) {
  const out = { name: p.name, type: p.type };
  if (p.components) out.components = p.components.map(param);
  return out;
}

function generate() {
  const iface = {};
  const errors = {};
  const deploy = {};
  for (const name of CONTRACTS) {
    const a = artifact(name);
    const contract = new ethers.Interface(a.abi);
    deploy[name] = { abi: a.abi, bytecode: a.bytecode };
    const functions = {};
    for (const fn of USED[name]) {
      const fragment = contract.getFunction(fn);
      if (!fragment) throw new Error(`${name}.${fn} is not in the ABI`);
      const entry = a.abi.find((e) => e.type === "function" && e.name === fn);
      functions[fn] = { selector: fragment.selector, inputs: entry.inputs.map(param), outputs: entry.outputs.map(param) };
    }
    iface[name] = functions;
    for (const entry of a.abi.filter((e) => e.type === "error")) {
      const selector = contract.getError(entry.name).selector;
      errors[selector] = { name: entry.name, inputs: entry.inputs.map(param) };
    }
  }
  // Solidity's own Error(string) and Panic(uint256).
  errors["0x08c379a0"] = { name: "Error", inputs: [{ name: "message", type: "string" }] };
  errors["0x4e487b71"] = { name: "Panic", inputs: [{ name: "code", type: "uint256" }] };
  const sorted = Object.fromEntries(Object.entries(errors).sort(([a], [b]) => (a < b ? -1 : 1)));

  const abiTs =
    "// Generated by contracts/scripts/export.cjs from the compiled contracts (npm run export in\n" +
    "// contracts/). Do not edit by hand; contracts/test/export.spec.cjs checks it is up to date.\n\n" +
    'import type { AbiFunction, AbiError } from "./codec";\n\n' +
    `export const FUNCTIONS = ${JSON.stringify(iface, null, 2)} as const satisfies Record<string, Record<string, AbiFunction>>;\n\n` +
    `export const ERRORS: Record<string, AbiError> = ${JSON.stringify(sorted, null, 2)};\n`;

  const deployJs =
    "// Generated by contracts/scripts/export.cjs (npm run export). Do not edit by hand.\n" +
    `export const CONTRACTS = ${JSON.stringify(deploy)};\n`;
  return { [path.join(ROOT, "..", "src", "world", "chain", "abi.ts")]: abiTs, [path.join(ROOT, "deploy", "contracts.js")]: deployJs };
}

function main() {
  const files = generate();
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, text] of Object.entries(files)) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === text) continue;
    if (check) {
      console.error(`${path.relative(process.cwd(), file)} is out of date: run npm run export in contracts/`);
      stale++;
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`wrote ${path.relative(process.cwd(), file)}`);
    }
  }
  if (stale) process.exit(1);
}

module.exports = { generate };
if (require.main === module) main();
